#!/usr/bin/env python3
"""打包使用手册。

help/*.md 是手册的唯一来源。本脚本：
  1. 从 js/perm.js 解析菜单与按钮权限，生成 help/permcodes.md（权限码清单，避免手工维护不一致）；
  2. 把全部章节打包为 js/help_content.js（window.HELP_MD），使 index.html 以 file:// 打开也能阅读手册；
  3. 合并为 docs/用户使用手册.md（可单独分发 / 转 Word、PDF）。

用法：python tools/build_help.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
HELP = ROOT / 'help'
ORDER = ['quickstart', 'install', 'login', 'overview', 'inspect', 'query', 'nodes', 'deploy', 'upgrade', 'backup',
         'load', 'param', 'alert', 'permission', 'platform', 'permcodes', 'faq', 'changelog']


def build_permcodes():
    src = (ROOT / 'js' / 'perm.js').read_text(encoding='utf-8')
    tree = src[src.index('const PERM_TREE'):src.index('/* 扁平化索引')]
    out = ['# 权限码清单', '',
           '> 本页由 `tools/build_help.py` 根据 `js/perm.js` 自动生成，请勿手工编辑。● 表示高危操作（执行前需输入集群名确认，可配置双人复核）。', '',
           '> 例外：**页面水印**的自定义不通过权限码授权，固定只有拥有「超级管理员」角色的用户可以修改。', '']
    total = 0
    for g in re.finditer(r"\{group: '([^']+)', menus: \[(.*?)\n  \]\}", tree, re.S):
        out += ['## ' + g.group(1), '', '| 菜单 | 权限码 | 权限名称 | 高危 |', '|---|---|---|---|']
        for m in re.finditer(r"\{id: '([^']+)', ico: '[^']*', name: '([^']+)', btns: \[(.*?)\](?:, public: true)?\}", g.group(2), re.S):
            mid, mname, body = m.groups()
            out.append(f'| **{mname}** | `{mid}:view` | 查看（显示菜单、打开页面） | |')
            total += 1
            for b in re.finditer(r"\['([\w.]+)', '([^']+)'(?:, '(\w+)')?\]", body):
                out.append(f'| | `{b.group(1)}` | {b.group(2)} | {"●" if b.group(3) == "high" else ""} |')
                total += 1
        out.append('')
    out.insert(6, f'共 **{total}** 个权限码。')
    out.insert(7, '')
    (HELP / 'permcodes.md').write_text('\n'.join(out), encoding='utf-8')
    return total


def build_go_perms():
    """从 js/perm.js 生成服务端权限树 backend/internal/perm/tree_gen.go（与前端共用同一份权限定义）。"""
    src = (ROOT / 'js' / 'perm.js').read_text(encoding='utf-8')
    tree = src[src.index('const PERM_TREE'):src.index('/* 扁平化索引')]
    out = ['// @author: kevinkelly', '// @license: Apache Licence', '// @file: tree_gen.go', '// @time: 2026/10/28', '',
           '// Code generated by tools/build_help.py from js/perm.js. DO NOT EDIT.', '', 'package perm', '',
           '// Tree 是全部菜单与按钮权限（与前端 PERM_TREE 一致）。', 'var Tree = []Group{']
    for g in re.finditer(r"\{group: '([^']+)', menus: \[(.*?)\n  \]\}", tree, re.S):
        out.append('\t{Name: %s, Menus: []Menu{' % json.dumps(g.group(1), ensure_ascii=False))
        for m in re.finditer(r"\{id: '([^']+)', ico: '[^']*', name: '([^']+)', btns: \[(.*?)\](, public: true)?\}", g.group(2), re.S):
            mid, mname, body, pub = m.groups()
            btns = ', '.join('{Code: %s, Name: %s%s}' % (json.dumps(b.group(1)), json.dumps(b.group(2), ensure_ascii=False), ', High: true' if b.group(3) == 'high' else '')
                             for b in re.finditer(r"\['([\w.]+)', '([^']+)'(?:, '(\w+)')?\]", body))
            out.append('		{ID: %s, Name: %s, Public: %s, Btns: []Btn{%s}},' % (json.dumps(mid), json.dumps(mname, ensure_ascii=False), 'true' if pub else 'false', btns))
        out.append('	}},')
    out.append('}')
    d = ROOT / 'backend' / 'internal' / 'perm'
    d.mkdir(parents=True, exist_ok=True)
    with open(d / 'tree_gen.go', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


def main():
    build_go_perms()
    n = build_permcodes()
    md = {k: (HELP / f'{k}.md').read_text(encoding='utf-8') for k in ORDER}
    js = ('// @author: kevinkelly\n// @license: Apache Licence\n// @file: help_content.js\n// @time: 2026/10/28\n\n'
          '/* 自动生成：python tools/build_help.py（来源 help/*.md），请勿手工编辑 */\n'
          'window.HELP_MD = ' + json.dumps(md, ensure_ascii=False, indent=0) + ';\n')
    (ROOT / 'js' / 'help_content.js').write_text(js, encoding='utf-8')

    titles = [re.match(r'#\s+(.*)', md[k]).group(1) for k in ORDER]
    ver = (ROOT / 'VERSION').read_text(encoding='utf-8').strip()
    doc = ['# StarRocks 运维平台 · 用户使用手册', '', f'版本 {ver}（原型）', '',
           '> 由 `help/*.md` 合并生成（`python tools/build_help.py`）。平台内可通过顶栏「? 帮助」或左侧「使用手册」阅读同一内容。', '',
           '## 目录', ''] + [f'{i + 1}. {t}' for i, t in enumerate(titles)] + ['']
    for i, k in enumerate(ORDER):
        body = re.sub(r'^# .*\n', '', md[k], count=1)
        body = re.sub(r'^(#{2,3}) ', lambda m: '#' + m.group(1) + ' ', body, flags=re.M)   # 章节内标题下沉一级
        doc += ['', '---', '', f'## {i + 1}. {titles[i]}', body.strip(), '']
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs' / '用户使用手册.md').write_text('\n'.join(doc), encoding='utf-8')
    stamp_assets(ver)
    print(f'ok: {len(ORDER)} 章，{n} 个权限码 -> js/help_content.js, docs/用户使用手册.md；index.html 资源版本 {ver}')


def stamp_assets(ver):
    """给 index.html 中的 css / js 引用加 ?v=<版本>，发布新版本后浏览器不会继续使用缓存的旧文件。"""
    p = ROOT / 'index.html'
    s = p.read_text(encoding='utf-8')
    s = re.sub(r'((?:href|src)="(?:css|js)/[\w.]+\.(?:css|js))(?:\?v=[^"]*)?"', lambda m: f'{m.group(1)}?v={ver.lstrip("v")}"', s)
    p.write_text(s, encoding='utf-8')


if __name__ == '__main__':
    main()
